type Translations = typeof ZH;

export const translations = { zh: ZH, en: EN as Translations };

export const LangContext = createContext<{ lang: Lang; t: Translations; setLang: (l: Lang) => void }>({
  lang: "zh",
  t: ZH as any,
  setLang: () => {},
});

export function LangProvider({ children }: { children: any }) {
  const [lang, setLangState] = useState<Lang>(() => (localStorage.getItem("lang") as Lang) || "zh");
  const t = lang === "zh" ? translations.zh : translations.en;
  const setLang = (l: Lang) => { setLangState(l); localStorage.setItem("lang", l); };
  return <LangContext.Provider value={{ lang, t: t as any, setLang }}>{children}</LangContext.Provider>;
}

export const useI18n = () => useContext(LangContext);
